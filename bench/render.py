"""Render each render spec as an HTML report, with Jinja2.

Every printed string comes from the render spec; the templates only lay it
out. So what a report shows is exactly what its spec says, and the spec stays
the one description of the page that stage 1 is scored against.

Layout variation is CSS, quick to change. Each results row carries
data-row, its index in the spec, so a self-check can find each printed value
inside its own row rather than anywhere on the page.

    uv run python -m bench.render

writes bench/data/reports/R01.html and so on.
"""

from datetime import date
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, StrictUndefined, select_autoescape

from bench.spec import RENDER_SPEC, RenderSpec

TEMPLATES = Path(__file__).resolve().parent / "templates"
OUT = Path(__file__).resolve().parent / "data" / "reports"

# Printed labels per language.
LABELS: dict[str, dict[str, str]] = {
    "en": {
        "title": "Laboratory Report",
        "patient": "Patient",
        "patient_id": "Patient ID",
        "accession": "Accession",
        "dob": "DOB",
        "collected": "Collected",
        "reported": "Reported",
        "physician": "Ordering",
        "cbc": "Complete Blood Count (CBC) with Differential",
        "chemistry": "Comprehensive Metabolic Panel and hs-CRP",
        "test": "Test",
        "result": "Result",
        "flag": "Flag",
        "previous": "Previous",
        "units": "Units",
        "reference": "Reference Interval",
        "page": "Page {number} of {total}",
        "synthetic": "Synthetic report generated by lab2clock. Not a real patient.",
        "date_format": "%m/%d/%Y",
    },
}

# US letter for English reports.
PAGE = {"en": ("Letter", "8.5in", "11in")}


def day(value: date, labels: dict[str, str]) -> str:
    """A date as the report's language prints it."""
    return value.strftime(labels["date_format"])


def environment() -> Environment:
    env = Environment(
        loader=FileSystemLoader(TEMPLATES),
        autoescape=select_autoescape(["j2"]),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.filters["day"] = day
    return env


def render_html(spec: RenderSpec, env: Environment | None = None) -> str:
    """The HTML report for `spec`."""
    env = env or environment()
    language = spec.conditions.language
    size, width, height = PAGE[language]
    template = env.get_template(f"{spec.conditions.layout}.html.j2")
    return template.render(
        spec=spec,
        t=LABELS[language],
        pages=sorted({row.page for row in spec.rows}),
        page_size=size,
        page_width=width,
        page_height=height,
    )


def main() -> None:
    env = environment()
    OUT.mkdir(parents=True, exist_ok=True)
    written, skipped = [], []
    for path in sorted(RENDER_SPEC.glob("*.json")):
        spec = RenderSpec.model_validate_json(path.read_text())
        if spec.conditions.language not in LABELS:
            skipped.append(spec.report)
            continue
        (OUT / f"{spec.report}.html").write_text(render_html(spec, env))
        written.append(spec.report)
    print(f"wrote {len(written)} reports to {OUT}")
    if skipped:
        print(f"skipped {', '.join(skipped)}: no labels for their language yet")


if __name__ == "__main__":
    main()
